DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'timeline_app') THEN
        CREATE ROLE timeline_app NOLOGIN;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO timeline_app;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO timeline_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO timeline_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO timeline_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO timeline_app;

REVOKE UPDATE ON TABLE audit_log FROM timeline_app;
